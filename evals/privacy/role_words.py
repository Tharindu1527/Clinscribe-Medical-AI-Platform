"""Role words taken for names (ADR-0029): "Patient", "Wife" at the start of a note sentence.

The fine-tuned tagger (ADR-0014) replaced "Patient" in "Patient has been really thirsty for about
three weeks." with a surrogate, in a doctor's edit (ADR-0028). The engine now drops a model's name
or place guess that is a role word alone (`privacy/deid/engine.py` ROLE_WORDS; cue-based matches
such as "Mr Son" are kept). This measures both engines with the filter off and on, on:
- PHI-free v3 (`clinical_negatives.SENTENCES_V3`): 40 note-style sentences with role words,
  written and frozen before any engine ran on them; any change is an over-redaction;
- role words next to a synthetic name (`ROLE_NAMES`): the name must still be replaced;
- the earlier sets, through `evals/privacy/lora_eval.evaluate`: seeded and held-out v1-v3 name and
  place recall, PHI-free v1 and v2 over-redaction (they should not change).
The tagger runs only when its model is present (`DEID_TAGGER_PATH`, git-ignored data/).

  uv run python -m evals.privacy.role_words     writes evals/reports/privacy/role_words.md
"""

import sys
from pathlib import Path
from typing import Any

import privacy.deid.engine as engine
from config.settings import Settings
from evals.privacy.clinical_negatives import ROLE_NAMES, SENTENCES_V3
from evals.privacy.deid_eval import deidentifier_for
from evals.privacy.lora_eval import evaluate
from privacy.deid.engine import Deidentifier

ROOT = Path(__file__).resolve().parents[2]
REPORT = ROOT / "evals" / "reports" / "privacy" / "role_words.md"


def measure(deidentifier: Deidentifier) -> dict[str, Any]:
    altered = [
        (s, out)
        for i, s in enumerate(SENTENCES_V3)
        if (out := deidentifier.deidentify(s, f"roles-{i}").text.text) != s
    ]
    names = [
        name not in deidentifier.deidentify(s, f"role-names-{i}").text.text
        for i, (s, name) in enumerate(ROLE_NAMES)
    ]
    return {"altered": altered, "names": (sum(names), len(names)), **evaluate(deidentifier)}


def run(ner: str, settings: Settings, filtered: bool) -> dict[str, Any]:
    saved = engine.ROLE_WORDS
    if not filtered:
        engine.ROLE_WORDS = frozenset()
    try:
        return measure(deidentifier_for(ner, settings.deid_spacy_model, settings.deid_tagger_path))
    finally:
        engine.ROLE_WORDS = saved


def _ratio(counts: tuple[int, int]) -> str:
    return f"{counts[0]}/{counts[1]}"


def report(results: dict[tuple[str, bool], dict[str, Any]]) -> str:
    lines = [
        "# Role words taken for names (ADR-0029)",
        "",
        "Generated by `evals/privacy/role_words.py`. PHI-free v3: 40 note-style sentences with "
        "role words, frozen before any engine ran on them (a change is an over-redaction). "
        "Role + name: 10 sentences where a synthetic name follows a role word (the name must be "
        "replaced). The other columns are the earlier sets (`evals/privacy/lora_eval.py`).",
        "",
        "| engine | role-word filter | PHI-free v3 altered | role + name: names replaced "
        "| PHI-free v1 / v2 altered | names held-out v1 / v3 | places held-out v1 / v3 |",
        "|---|---|---|---|---|---|---|",
    ]
    for (ner, on), r in results.items():
        lines.append(
            f"| {ner} | {'on' if on else 'off'} | {len(r['altered'])}/{len(SENTENCES_V3)} | "
            f"{_ratio(r['names'])} | {_ratio(r['negatives_v1'])} / {_ratio(r['negatives_v2'])} | "
            f"{_ratio(r['heldout_v1']['PERSON'])} / {_ratio(r['heldout_v3']['PERSON'])} | "
            f"{_ratio(r['heldout_v1']['LOCATION'])} / {_ratio(r['heldout_v3']['LOCATION'])} |"
        )
    for (ner, on), r in results.items():
        if r["altered"]:
            lines += ["", f"PHI-free v3 altered, {ner}, filter {'on' if on else 'off'}:", ""]
            lines += [f"- {s} -> {out}" for s, out in r["altered"]]
    lines += [
        "",
        "PHI-free v3 was written to target this error, after it was seen once, so it shows that "
        "the filter removes it, not how common it is in real notes. The filter cannot hide a name "
        "standing next to the role word (the span is then longer than the role word) or after a "
        "cue such as 'Mr' (cue-based matches are not filtered).",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    settings = Settings()
    engines = ["spacy"]
    if settings.deid_tagger_path and Path(settings.deid_tagger_path).exists():
        engines.append("tagger")
    results = {(ner, on): run(ner, settings, on) for ner in engines for on in (False, True)}
    for (ner, on), r in results.items():
        print(
            ner,
            "filter",
            "on" if on else "off",
            "v3 altered",
            len(r["altered"]),
            "names",
            r["names"],
        )
    REPORT.write_text(report(results), encoding="utf-8", newline="\n")
    print(f"wrote {REPORT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
