"""Grounding the question's subject, offline (ADR-0017 follow-up): two deterministic checks that
would have stopped the wrong-drug answer (mazdutide answered from the semaglutide label).

(a) unseen term: a question word (5+ letters, BM25 tokenizer) that appears nowhere in the corpus
    (chunk text, titles, sections); the sources cannot be about it, so the answer should abstain.
(b) drug grounding: every drug the question names (drug lexicon: DDInter + RxNorm names, aliases
    and brands) must be named in at least one cited source.

Measured on all 235 golden questions for (a), and on every stored answer (evals/reports/rag/
answers/*.jsonl) for (b). Caveat: the golden unanswerable questions were built as "a drug absent
from the corpus", so (a)'s catch rate there is optimistic; its false blocks on answerable questions
are the honest number. No LLM calls.

  uv run python -m evals.rag.drug_grounding
Writes evals/reports/rag/drug_grounding.md.
"""

import json
import sys
from collections import Counter
from pathlib import Path

from evals.golden.golden import load_items
from retrieval.bm25 import tokenize
from retrieval.graph.lexicon import DrugLexicon
from retrieval.graph.load import GRAPH_DIR, read_jsonl

ROOT = Path(__file__).resolve().parents[2]
CORPUS = ROOT / "data" / "corpus"
ANSWERS = ROOT / "evals" / "reports" / "rag" / "answers"
REPORT = ROOT / "evals" / "reports" / "rag" / "drug_grounding.md"
SYSTEMS = ("dense", "hybrid_colbert", "hybrid_colbert_ctx", "hybrid_colbert_ctx_v2")
MIN_CHARS = 5


def corpus_vocabulary() -> tuple[Counter[str], dict[str, str]]:
    """Document frequency of every token in the corpus, and chunk id -> 'title section text'."""
    docs = {d["id"]: d for d in read_jsonl(CORPUS / "docs.jsonl")}
    df: Counter[str] = Counter()
    texts: dict[str, str] = {}
    for chunk in read_jsonl(CORPUS / "chunks.jsonl"):
        text = f"{docs[chunk['doc_id']]['title']} {chunk['section']} {chunk['text']}"
        texts[chunk["id"]] = text
        df.update(set(tokenize(text)))
    return df, texts


def spellings(term: str) -> set[str]:
    """British and American spellings of a term (nebulised/nebulized, haemoglobin/hemoglobin)."""
    variants = {term}
    for uk, us in (("isation", "ization"), ("ise", "ize"), ("ising", "izing"), ("our", "or"),
                   ("ae", "e"), ("oe", "e")):  # fmt: skip
        variants |= {v.replace(uk, us) for v in variants}
    return variants


def unseen_terms(
    question: str, df: Counter[str], english: object = None, fold: bool = False
) -> list[str]:
    """Question words of 5+ letters the corpus never uses; with `english` (a spaCy vocabulary),
    common English words do not count; with `fold`, nor do UK/US spellings of corpus words."""
    terms = []
    for t in tokenize(question):
        if len(t) < MIN_CHARS or not t.isalpha() or df[t]:
            continue
        if fold and any(df[v] for v in spellings(t)):
            continue
        if english is not None and english.has_vector(t):  # type: ignore[attr-defined]
            continue
        terms.append(t)
    return terms


def main() -> int:
    df, texts = corpus_vocabulary()
    lexicon = DrugLexicon(read_jsonl(GRAPH_DIR / "drugs.jsonl"))
    items = load_items()
    lines = [
        "# Grounding the question's subject: unseen terms and drug names",
        "",
        "Generated by `evals/rag/drug_grounding.py` (no LLM calls). See its docstring for the",
        "caveat on (a): the unanswerable golden questions were built around drugs absent from the",
        "corpus, so their catch rate is optimistic; false blocks on answerable questions are not.",
        "",
        "## (a) Unseen term in the question (all 235 golden questions)",
        "",
        "Variants: a word the corpus never uses; and not a common English word (spaCy",
        "`en_core_web_md` has a vector for it); and not a UK/US spelling of a corpus word (added",
        "after seeing the one false block it removes, so optimistic for that case).",
        "",
        "| Variant | Answerable flagged (of 209) | Unanswerable flagged (of 26) | "
        "Unanswerable missed |",
        "|---|---|---|---|",
    ]
    import spacy

    vocab = spacy.load("en_core_web_md").vocab
    variants = {
        "unseen": {},
        "unseen, not English": {"english": vocab},
        "unseen, not English, spelling folded": {"english": vocab, "fold": True},
    }
    flagged_by: dict[str, list[tuple[str, str, list[str]]]] = {}
    for name, options in variants.items():
        hits = [(i, unseen_terms(i.question, df, **options)) for i in items]  # type: ignore[arg-type]
        flagged = [(i, terms) for i, terms in hits if terms]
        answerable = [(i.id, i.question, terms) for i, terms in flagged if i.answerable]
        caught = {i.id for i, _ in flagged if not i.answerable}
        missed = [f"{i.id} {i.question}" for i in items if not i.answerable and i.id not in caught]
        flagged_by[name] = answerable
        lines.append(f"| {name} | {len(answerable)} | {len(caught)} | {'; '.join(missed) or '-'} |")
    for name, answerable in flagged_by.items():
        lines += ["", f"False blocks, {name}:", ""]
        lines += [f"- {qid}: {q} (unseen: {', '.join(t)})" for qid, q, t in answerable] or [
            "- none"
        ]

    lines += [
        "",
        "## (b) Every drug the question names is named in a cited source (stored answers)",
        "",
        "| System | Answers given | Question names a drug | Would be blocked | Blocked, answerable "
        "(correctness of those) | Blocked, unanswerable |",
        "|---|---|---|---|---|---|",
    ]
    blocked_rows: list[str] = []
    gold = {i.id: i for i in items}
    for system in SYSTEMS:
        path = ANSWERS / f"{system}.jsonl"
        if not path.exists():
            continue
        rows = {r["id"]: r for r in map(json.loads, path.read_text("utf-8").splitlines())}
        given = [r for r in rows.values() if not r["answer"]["abstained"]]
        named = blocked = 0
        blocked_answerable: list[float] = []
        blocked_unanswerable = 0
        for row in given:
            wanted = lexicon.find(gold[row["id"]].question)
            if not wanted:
                continue
            named += 1
            cited = {c for s in row["answer"]["sentences"] for c in s["chunk_ids"]}
            found = set().union(*(lexicon.find(texts[c]) for c in cited if c in texts))
            missing = {lexicon.names[k] for k in wanted if not _same_drug(lexicon, k, found)}
            if missing:
                blocked += 1
                if gold[row["id"]].answerable:
                    blocked_answerable.append(row["metrics"].get("correctness", 0.0))
                else:
                    blocked_unanswerable += 1
                blocked_rows.append(
                    f"- {system} {row['id']}: {gold[row['id']].question} (not in the cited "
                    f"sources: {', '.join(sorted(missing))}; correctness "
                    f"{row['metrics'].get('correctness')})"
                )
        correct = ", ".join(str(c) for c in blocked_answerable) or "-"
        lines.append(
            f"| {system} | {len(given)} | {named} | {blocked} | {len(blocked_answerable)} "
            f"({correct}) | {blocked_unanswerable} |"
        )
    lines += ["", "Answers (b) would block:", "", *(blocked_rows or ["- none"])]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


def _same_drug(lexicon: DrugLexicon, key: str, found: set[str]) -> bool:
    """The drug, or another formulation of the same ingredient, is named in the sources."""
    return key in found or lexicon.identity.get(key) in {lexicon.identity.get(f) for f in found}


if __name__ == "__main__":
    sys.exit(main())
