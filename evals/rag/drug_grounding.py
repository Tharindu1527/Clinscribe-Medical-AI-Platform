"""Grounding the question's subject, offline (ADR-0018): the two deterministic checks in
retrieval/grounding.py, which would have stopped the wrong-drug answer (mazdutide answered from the
semaglutide label, ADR-0017).

(a) unseen terms, on all 235 golden questions, in three variants: a word the corpus never uses;
    and not a common English word; and not a UK/US spelling of a corpus word.
(b) drugs the question names that no cited source names, on every stored answer
    (evals/reports/rag/answers/*.jsonl).

Caveat: the golden unanswerable questions were built as "a drug absent from the corpus", so (a)'s
catch rate there is optimistic; its false blocks on answerable questions are the honest number.
No LLM calls.

  uv run python -m evals.rag.drug_grounding
Writes evals/reports/rag/drug_grounding.md.
"""

import json
import sys
from pathlib import Path

from evals.golden.golden import load_items
from retrieval.dense import load_chunks
from retrieval.graph.lexicon import DrugLexicon
from retrieval.graph.load import GRAPH_DIR, read_jsonl
from retrieval.grounding import Grounding

ROOT = Path(__file__).resolve().parents[2]
ANSWERS = ROOT / "evals" / "reports" / "rag" / "answers"
REPORT = ROOT / "evals" / "reports" / "rag" / "drug_grounding.md"
SYSTEMS = ("dense", "hybrid_colbert", "hybrid_colbert_ctx", "hybrid_colbert_ctx_v2")
VARIANTS = {
    "unseen": {"english": False, "fold": False},
    "unseen, not English": {"english": True, "fold": False},
    "unseen, not English, spelling folded (production)": {"english": True, "fold": True},
}


def main() -> int:
    import spacy

    vocab = spacy.load("en_core_web_md").vocab
    grounding = Grounding(
        load_chunks()[0], vocab.has_vector, DrugLexicon(read_jsonl(GRAPH_DIR / "drugs.jsonl"))
    )
    items = load_items()
    lines = [
        "# Grounding the question's subject: unseen terms and drug names",
        "",
        "Generated by `evals/rag/drug_grounding.py` with `retrieval/grounding.py` (no LLM calls).",
        "The unanswerable golden questions were built around drugs absent from the corpus, so the",
        "catch rate is optimistic; false blocks on answerable questions are not. The spelling fold",
        "was added after seeing the one false block it removes (nebulised), so optimistic there.",
        "",
        "## (a) Unseen term in the question (all 235 golden questions)",
        "",
        "| Variant | Answerable flagged (of 209) | Unanswerable flagged (of 26) | "
        "Unanswerable missed |",
        "|---|---|---|---|",
    ]
    flagged_by: dict[str, list[str]] = {}
    for name, options in VARIANTS.items():
        hits = [(i, grounding.unseen_terms(i.question, **options)) for i in items]
        flagged = [(i, terms) for i, terms in hits if terms]
        flagged_by[name] = [
            f"{i.id}: {i.question} (unseen: {', '.join(terms)})"
            for i, terms in flagged
            if i.answerable
        ]
        caught = {i.id for i, _ in flagged if not i.answerable}
        missed = [f"{i.id} {i.question}" for i in items if not i.answerable and i.id not in caught]
        lines.append(
            f"| {name} | {len(flagged_by[name])} | {len(caught)} | {'; '.join(missed) or '-'} |"
        )
    for name, false_blocks in flagged_by.items():
        lines += ["", f"False blocks, {name}:", ""]
        lines += [f"- {row}" for row in false_blocks] or ["- none"]

    lines += [
        "",
        "## (b) Every drug the question names is named in a cited source (stored answers)",
        "",
        "| System | Answers given | Would be blocked | Blocked, answerable (correctness) | "
        "Blocked, unanswerable |",
        "|---|---|---|---|---|",
    ]
    blocked_rows: list[str] = []
    gold = {i.id: i for i in items}
    for system in SYSTEMS:
        path = ANSWERS / f"{system}.jsonl"
        if not path.exists():
            continue
        rows = [json.loads(line) for line in path.read_text("utf-8").splitlines()]
        given = [r for r in rows if not r["answer"]["abstained"]]
        correctness: list[str] = []
        unanswerable = 0
        for row in given:
            item = gold[row["id"]]
            cited = [c for s in row["answer"]["sentences"] for c in s["chunk_ids"]]
            missing = grounding.missing_drugs(item.question, cited)
            if not missing:
                continue
            if item.answerable:
                correctness.append(str(row["metrics"].get("correctness")))
            else:
                unanswerable += 1
            blocked_rows.append(
                f"- {system} {row['id']}: {item.question} (not in the cited sources: "
                f"{', '.join(missing)})"
            )
        lines.append(
            f"| {system} | {len(given)} | {len(correctness) + unanswerable} | "
            f"{len(correctness)} ({', '.join(correctness) or '-'}) | {unanswerable} |"
        )
    lines += ["", "Answers (b) would block:", "", *(blocked_rows or ["- none"])]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
